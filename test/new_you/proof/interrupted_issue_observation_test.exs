defmodule NewYou.Proof.InterruptedIssueObservationTest do
  use ExUnit.Case, async: false

  alias Ecto.Adapters.SQL.Sandbox
  alias NewYou.{Identity, Repo}
  alias NewYou.Proof.{FixtureObservation, P805, P809Catalog, SelfTest}

  for consequence <- [:foreign, :tokens, :sessions] do
    test "interrupted issuance observes #{consequence} consequences by creation owner" do
      exercise(unquote(consequence))
    end
  end

  defp exercise(consequence) do
    operation = Ecto.UUID.generate()
    email = "proof-#{operation}@example.test"

    request =
      P805.with_fixture(fn -> %{P805.request() | operation_id: operation, email: email} end)

    try do
      parent = self()
      reference = make_ref()
      handler = {__MODULE__, reference}

      registration =
        Enum.find(P809Catalog.registrations(), &(&1.case_id == "p809.interrupted_issue"))

      :ok =
        :telemetry.attach(handler, [:new_you, :repo, :query], &__MODULE__.baseline_barrier/4, {
          parent,
          reference
        })

      task = Task.async(fn -> execute(registration, reference) end)

      try do
        assert_receive {^reference, :baseline, worker, context}, 5_000

        try do
          FixtureObservation.with_scope(fn ->
            Sandbox.unboxed_run(Repo, fn ->
              assert {:ok, foreign} = Identity.register(request)
              assert {:ok, :verified} = Identity.verify_email(foreign.verification_proof)

              assert {:ok, credentials} =
                       Identity.authenticate_password(request.email, request.password)

              session = Ash.get!(Identity.Session, credentials.session_id, authorize?: false)
              before = fingerprint()
              probe = Ecto.UUID.generate()

              try do
                FixtureObservation.with_context(context, fn ->
                  insert_probe(consequence, foreign.account_id, session.token_jti, probe)
                end)

                send(worker, {reference, :continue})
                {result, cleanup} = Task.await(task, 15_000)
                assert_receive {^reference, :backend, ^context, terminated_backend}, 5_000

                assert P805.scalar("SELECT count(*) FROM pg_stat_activity WHERE pid = $1", [
                         terminated_backend
                       ]) == 0

                if consequence == :foreign do
                  assert result["verdict"] == "PASS", inspect(result)
                  assert result["assertion_ids"] == registration.manifest.assertion_ids
                else
                  assert result["verdict"] == "FAIL"
                  assert "assertion.failed" in result["reason_codes"]

                  assert %{"code" => "p809.interrupted_issue.atomic_rollback", "value" => false} in result[
                           "observations"
                         ]
                end

                assert Enum.all?(cleanup, fn {_key, value} -> value == true end)
                assert fingerprint() == before
              after
                # These exact keys were generated by this probe. Observation IDs
                # never become selectors for general fixture cleanup.
                Repo.query!("DELETE FROM sessions WHERE token_jti = $1", [probe])
                Repo.query!("DELETE FROM tokens WHERE jti = $1", [probe])
              end
            end)
          end)
        after
          send(worker, {reference, :continue})
        end
      after
        :telemetry.detach(handler)
        if Process.alive?(task.pid), do: Task.await(task, 15_000)
      end
    after
      P805.with_fixture(fn -> P805.request(%{operation_id: operation, email: email}) end)
    end
  end

  defp execute(registration, reference) do
    SelfTest.execute_registered_case(Map.put(registration.manifest, :version, "p8-08.1"), fn ->
      Process.put({__MODULE__, reference}, :armed)
      registration.callback.()
    end)
  end

  # Stop exactly once after A's second baseline read, on the SQL query caller.
  # The legacy and corrected forms are accepted so this barrier proves RED
  # against the original callback without replacing its implementation.
  def baseline_barrier(_event, _measurements, metadata, {parent, reference}) do
    if metadata.query == "SELECT pg_backend_pid()" do
      with {:ok, %{rows: [[backend]]}} <- metadata.result do
        send(parent, {reference, :backend, FixtureObservation.context(), backend})
      end
    end

    baseline? =
      metadata.query == "SELECT count(*) FROM sessions" or
        String.starts_with?(metadata.query, "SELECT row_to_json(owned)::text FROM sessions owned")

    if baseline? and Process.get({__MODULE__, reference}) == :armed do
      Process.put({__MODULE__, reference}, :reached)
      send(parent, {reference, :baseline, self(), FixtureObservation.context()})

      receive do
        {^reference, :continue} -> :ok
      after
        10_000 -> raise "interrupted issuance owner barrier deadline"
      end
    end
  end

  defp insert_probe(:foreign, _account_id, _token_jti, _probe), do: :ok

  defp insert_probe(:tokens, _account_id, token_jti, probe) do
    assert %{num_rows: 1} =
             Repo.query!(
               """
               INSERT INTO tokens (jti, subject, expires_at, purpose, extra_data, account_id)
               SELECT $1, subject, expires_at, purpose, extra_data, account_id FROM tokens WHERE jti = $2
               RETURNING jti
               """,
               [probe, token_jti]
             )
  end

  defp insert_probe(:sessions, account_id, _token_jti, probe) do
    now = DateTime.utc_now() |> DateTime.truncate(:second)

    Ash.create!(
      Identity.Session,
      %{
        account_id: account_id,
        token_jti: probe,
        expires_at: DateTime.add(now, 300),
        idle_expires_at: DateTime.add(now, 300),
        last_seen_at: now
      },
      action: :issue,
      authorize?: false
    )
  end

  defp fingerprint,
    do: {FixtureObservation.fingerprint(:tokens), FixtureObservation.fingerprint(:sessions)}
end
